// Here we build a function by name Restaurant()
function getRestaurant(restaurants) {
  const root = document.getElementById("root");

  restaurants.forEach((restaurant) => {
    // Here we start creating a card
    // like this : <div class="card">
    //     <div class="image">
    //       <img src="./image.png" alt="image" />
    //       <p>
    //         <img
    //           class="percentage"
    //           src="https://b.zmtcdn.com/data/o2_assets/c0e0fe766225fb9cdb3245a9915571201716296953.png"
    //           alt=""
    //         />
    //         Flat 50% OFF
    //       </p>
    //     </div>
    //     <div class="restuarant">
    //       <div class="name box">Raghvam Cafe & Restaurant</div>
    //       <div class="rating box">
    //         4.4<img src="./star.svg" alt="star" class="rating-star" />
    //       </div>
    //     </div>
    //     <div class="details">
    //       <div class="food box">North Indian, Chinese</div>
    //       <div class="price box">₹1,000 for two</div>
    //     </div>
    //     <div class="location">
    //       <div class="address box">Jail Road, Indore</div>
    //       <div class="distance box">1.3 km</div>
    //     </div>
    //   </div>
    // Start creating card
    const card = document.createElement("div");
    card.classList = "card";

    // create a Image element
    const imageDiv = document.createElement("div");
    imageDiv.className = "image";

    const img = document.createElement("img");
    img.src = `Assets/${restaurant["Restaurant Images"]}.avif`;
    img.onerror = function () {
      this.src = `Assets/${restaurant["Restaurant Images"]}.jpg`;
    };

    imageDiv.appendChild(img);

    // Here we start creating card content

    // Card Header
    const restuarant = document.createElement("div");
    restuarant.className = "restuarant";

    const name = document.createElement("div");
    name.className = "name box";
    name.textContent = `${restaurant["Restaurant Name"]}`;

    const rating = document.createElement("div");
    rating.className = "rating box";
    rating.textContent = `${restaurant["Rating"]}`;

    const starImg = document.createElement("img");
    starImg.src = "./star.svg";
    starImg.alt = "star";
    starImg.className = "rating-star";
    rating.appendChild(starImg);

    restuarant.appendChild(name);
    restuarant.appendChild(rating);

    // Card Footer
    const details = document.createElement("div");
    details.className = "details";

    const food = document.createElement("div");
    food.className = "food box";
    food.textContent = `${restaurant["Food Type"]}`;

    const price = document.createElement("div");
    price.className = "price box";
    price.textContent = `₹ ${restaurant.Price}`;

    details.appendChild(food);
    details.appendChild(price);

    // Card Location
    const location = document.createElement("div");
    location.className = "location";

    const address = document.createElement("div");
    address.className = "address box";
    address.textContent = `${restaurant.Location}`;

    const distance = document.createElement("div");
    distance.className = "distance box";
    distance.textContent = `${restaurant.Distance} km`;

    location.appendChild(address);
    location.appendChild(distance);

    // Append all things in card)
    card.appendChild(imageDiv);
    card.appendChild(restuarant);
    card.appendChild(details);
    card.appendChild(location);

    root.appendChild(card);
  });
}
